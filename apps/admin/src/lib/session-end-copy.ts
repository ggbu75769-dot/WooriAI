/**
 * 라운드 107 트랙 J — **로그인 화면이 "왜 여기로 왔는지"를 말하는 한 자리.**
 *
 * ## 종전(그때는 참이었다) → 이제
 *
 * 종전 어드민에는 세션이 끝난 **이유를 나르는 채널이 0건**이었다. `isAuthError(error)`가 참인
 * 서른 자리가 전부 `clearSession(); return;` 하나로 끝났고, 그 다음 프레임에 셸이
 * `session === null`을 보고 로그인 화면을 그렸다. 그래서 저장 버튼을 누른 순간 세션이
 * 만료되면 **폼 내용째로 화면이 사라지고** 로그인 화면이 떴는데, 그것이 로그아웃당한 것인지
 * 앱이 깨진 것인지 말하는 자리가 어디에도 없었다(문장 0건).
 *
 * 이제 그 이유가 `admin-token-context.tsx`의 `lastEndReason`으로 로그인 화면까지 오고,
 * 이 모듈이 그 값 하나를 **문장 하나**로 바꾼다.
 *
 * ## 왜 이 형식인가 — 저장소가 이미 쓰는 방식
 *
 * 모바일이 AUTH-127에서 같은 결함을 같은 모양으로 고쳤다: `session.store.ts`가
 * `SessionEndReason`("logout" | "expired")을 들고 `clearSession(reason)`이 그 값을 남기면,
 * 로그인 화면이 그것을 읽어 `SESSION_EXPIRED_LOGIN_NOTICE` 한 줄을 세운다
 * (`apps/mobile/src/offline/messages.ts` · `src/offline/session-expiry.ts`). 어드민은 그
 * 형식을 그대로 빌리되 **문장은 빌리지 않는다** — 모바일의 문장은 *"다시 로그인하면 저장하지
 * 않은 기록도 이어서 반영할게요"* 라고 약속하는데, 그 약속은 모바일에 아웃박스가 있어서 참이다.
 * 어드민에는 아웃박스가 없고 폼 값은 컴포넌트가 언마운트되는 순간 사라지므로, 같은 문장을
 * 어드민에 붙이면 **지키지 못할 약속**이 된다(DNC-018: 단정·다그침 금지, 관찰과 다음 행동만).
 *
 * ## 이 모듈이 짓는 것과 짓지 않는 것
 *
 * · **짓는다** — 위 두 사실을 말하는 문장 둘. 어드민에는 이 자리에 쓸 문장이 종전에 0건이었다.
 * · **짓지 않는다** — 판정. 401 여부는 `admin-api.ts`의 `isAuthError`가, 조회 실패의 갈래는
 *   `load-error-copy.ts`가 이미 낸다. 여기는 이유 하나를 받아 문장 하나를 고를 뿐이다.
 *
 * ⚠️ **문장을 주석에 다시 적지 않는다.** 위 인용은 전부 모바일 쪽 문장이고, 아래 두 상수의
 * 글자는 이 파일에서 코드로만 존재한다 — 주석이 사본을 들면 그 문장을 무는 계약이 코드가
 * 사라져도 초록이 된다(`packages/test-utils`의 주석 관용 앵커 대장이 세는 그 자리).
 */

/**
 * 클라이언트 세션 캐시가 비워진 이유. 오늘 둘뿐이다.
 *
 * · `"rejected"` — **서버가 토큰을 거절했다**(401). 만료·폐기·다른 기기에서의 해제가 전부 이
 *   한 값으로 온다. ⚠️ 모바일은 같은 자리를 `"expired"`라고 부르는데, 어드민은 그 이름을
 *   빌리지 않는다: 어드민 가드가 내는 401은 `ADMIN_UNAUTHORIZED` 하나뿐이라
 *   (`apps/api/src/admin/admin-auth.guard.ts`) 만료와 폐기를 **클라이언트가 구별할 수 없고**,
 *   `"expired"`라는 이름은 그 구별을 아는 척한다.
 * · `"logout"` — 운영자가 스스로 눌렀다(로그아웃 · "다른 계정으로 로그인"). 이 경우 화면은
 *   아무 말도 하지 않는다 — 자기가 방금 누른 것을 되읽어 주는 것은 정보가 아니라 소음이다.
 */
export type AdminSessionEndReason = "rejected" | "logout";

/** 로그인 화면 맨 위에 서는 한 줄. `canRetry`가 참일 때만 그 옆에 [다시 시도]가 선다. */
export type AdminLoginNotice = { message: string; canRetry: boolean };

/**
 * 서버가 토큰을 거절해 로그인 화면으로 돌아온 경우.
 *
 * 세 조각이고 셋 다 **오늘 참인 사실**이다: ⓐ 무엇이 일어났는가(둘 중 하나라고만 말한다 —
 * 위 `"rejected"` 주석의 이유로 어느 쪽인지 알 수 없다), ⓑ 그래서 무엇을 잃었는가(폼 값은
 * 남지 않는다 — 이 라운드가 값 보존을 하지 않았으므로 이 문장이 참이다), ⓒ 다음 걸음.
 *
 * ⚠️ ⓑ를 적는 이유가 이 문장의 본체다. 운영자가 잃은 것을 말하지 않으면 그는 다시 로그인한
 * 뒤 자기가 치던 내용을 찾다가 두 번째로 잃는다.
 */
const SESSION_REJECTED_NOTICE =
  "세션이 만료됐거나 다른 곳에서 해제돼 로그인 화면으로 돌아왔어요. " +
  "저장하지 않은 입력은 남아 있지 않으니, 다시 로그인한 뒤 이어서 작업해 주세요.";

/**
 * 앱에 들어오면서 세션을 확인하려 했는데 **401이 아닌 이유로** 실패한 경우
 * (연결 실패 · 읽기 타임아웃 · 5xx). 종전에는 이 경우도 세션을 버리고 말없이 로그인 화면을
 * 세웠다 — 운영자는 로그아웃당한 것으로 읽었지만 실은 API가 잠깐 죽었을 뿐이었다.
 *
 * 가운데 문장이 **모른다고 말한다.** 클라이언트가 가진 사실은 "응답을 받지 못했다" 하나뿐이고,
 * 그 사실로는 세션의 생사를 알 수 없다 — 여기서 "로그아웃됐어요"라고 말하면 그것이 곧 허위다.
 */
const SESSION_CHECK_FAILED_NOTICE =
  "로그인 상태를 확인하지 못했어요. 로그아웃된 것인지 서버에 닿지 못한 것인지 아직 알 수 없어요. " +
  "다시 시도하거나, 아래에서 로그인해 주세요.";

/**
 * 로그인 화면이 세울 문장 하나(없으면 null — 처음 여는 사람에게는 아무 말도 하지 않는다).
 *
 * ⚠️ **순서가 값이다.** 둘은 오늘 동시에 참일 수 없지만(`admin-token-context.tsx`가 한쪽을
 * 세울 때 다른 쪽을 지운다) 이 함수는 그 사실에 기대지 않는다 — 확인 실패가 **더 나중의
 * 사실**이라 먼저 선다. 반대로 두면 어제 거절당한 세션의 문장이 오늘의 연결 실패를 덮는다.
 *
 * ⚠️ 확인 실패의 `canRetry`가 언제나 참인 이유: 401은 이 갈래에 오지 않으므로(호출부가 먼저
 * 갈랐다) 남은 것은 전부 "다음 번엔 닿을 수 있는" 실패다. 그리고 그 판정이 틀렸더라도 같은
 * 화면에 로그인 폼이 서 있어 운영자가 갇히지 않는다.
 */
export function adminLoginScreenNotice(input: {
  endReason: AdminSessionEndReason | null;
  sessionCheckFailed: boolean;
}): AdminLoginNotice | null {
  if (input.sessionCheckFailed) return { message: SESSION_CHECK_FAILED_NOTICE, canRetry: true };
  // 스스로 누른 로그아웃은 말하지 않는다(위 `"logout"` 주석).
  if (input.endReason === "rejected") return { message: SESSION_REJECTED_NOTICE, canRetry: false };
  return null;
}
