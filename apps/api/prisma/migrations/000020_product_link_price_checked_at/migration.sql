-- 라운드 51 #9: 판매처별 가격의 **기준 시각**.
--
-- `product_links.price_snapshot_krw`는 000001부터 있었고 어드민 벌크 교체(CSV)와 시드가
-- 값을 넣는데, 앱 응답에는 한 번도 실린 적이 없다. 그 값을 그대로 화면에 올리면 그
-- 자체가 허위 표시다 — 스냅샷은 "언젠가 확인한 값"이고, 언제 확인했는지 말하지 않으면
-- 사용자는 그것을 현재가로 읽는다. 그래서 가격을 노출하기 전에 기준 시각을 먼저 만든다.
--
-- 서버 규칙(apps/api/src/onboarding/items-catalog.service.ts toProductLinkDto):
-- price_checked_at이 NULL이면 가격도 내리지 않는다(둘 다 생략). 즉 이 컬럼이 없는
-- 값은 "확인 시각을 모르는 값"이고, 모르는 것은 표시하지 않는다.
--
-- 000009~000019와 같은 additive 관례: ADD COLUMN IF NOT EXISTS, NULL 허용, 기존 행 무영향.
-- 000001~000019는 수정하지 않는다(DNC-007).
--
-- **백필하지 않는 이유**: 이 테이블에서 시각처럼 보이는 유일한 값은 updated_at인데,
-- 그것은 "행이 마지막으로 수정된 시각"이지 "가격을 확인한 시각"이 아니다(제휴 URL만
-- 고친 행도 갱신된다). 그 값을 확인 시각으로 옮겨 적는 순간 서버가 지어낸 시각을
-- 말하게 되므로, 기존 행은 NULL로 남겨 두고 위 규칙에 따라 가격을 숨긴다. 시드가
-- 관리하는 링크는 다음 시드 실행이 자기 값(price_snapshot_krw)과 함께 이 컬럼을
-- 시드 시각으로 채운다(prisma/seed.ts) — 시드는 가격을 그 시점에 명시한 주체이므로
-- 그 시각이 곧 확인 시각이다.
--
-- 인덱스는 만들지 않는다: 이 컬럼을 술어로 쓰는 조회가 없다(항상 이미 뽑아 둔 링크
-- 행의 컬럼을 함께 읽을 뿐이다).
ALTER TABLE product_links ADD COLUMN IF NOT EXISTS price_checked_at timestamptz;
