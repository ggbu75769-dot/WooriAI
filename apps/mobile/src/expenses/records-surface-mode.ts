/**
 * 기록 탭의 **표면 판정** 순수 모듈 — "지금 이 화면은 무엇을 말할 수 있는 상태인가".
 *
 * ## 왜 생겼나 (이월 항목: 0건 사용자에게 서던 컨트롤 무더기)
 *
 * 종전에 `app/(tabs)/records.tsx`의 `listHeader`는 **검색 입력 · 분류 칩 줄 · 정렬 토글**을
 * 어떤 상태에서도 무조건 그렸다(그때는 참이었다 — 그 컨트롤들이 하나씩 붙던 라운드마다
 * "이 달에 목록이 있다"가 암묵 전제였고, 아무도 그 전제를 판정으로 적지 않았다). 그래서
 * 아직 아무것도 기록하지 않은 사람의 첫 화면이 **가리킬 대상이 하나도 없는 컨트롤 무더기**로
 * 시작했다: 무엇을 검색하고, 무엇을 분류로 좁히고, 무엇을 금액순으로 정렬하라는 것인지
 * 화면 안에 없다. 그 줄들이 세로 자리를 먹는 만큼 핵심 루프 1단계(지출 기록)로 가는 빈 상태
 * 카드는 아래로 밀린다.
 *
 * ## 이 모듈이 가르는 여섯 갈래 — ⚠️ 셋째와 다섯째를 섞으면 사용자가 갇힌다
 *
 *  · `"loading"`      — 아직 확정된 목록이 없다(조회 중이거나 쿼리가 비활성이다).
 *  · `"error"`        — 조회가 확정 실패했다.
 *  · `"empty"`        — 로드 성공 · **필터 0개** · 모집단 0건 · **다른 달에 기록이 있다는 반증도
 *    손에 없다**. **여기서만** 컨트롤을 걷는다.
 *  · `"empty-month"`  — 로드 성공 · 필터 0개 · 이 달 모집단 0건인데 **계정에 기록이 있다는 것을
 *    이미 손에 든 캐시가 말한다**. 이 달만 비었을 뿐 검색이 가리킬 대상이 앱 안에 있으므로
 *    컨트롤을 걷지 않는다(아래 "무엇이 바뀌었나" 참고).
 *  · `"filtered-empty"` — 로드 성공 · 필터가 걸렸고 그 결과가 0건. ⚠️ 여기서 컨트롤을 걷으면
 *    사용자가 **자기가 건 필터를 되돌릴 수단을 잃는다**(검색어를 지울 입력칸도, 칩을 풀
 *    "전체"도 사라진다). 그래서 이 갈래는 `"list"`와 **같은 편**에 선다.
 *  · `"list"`         — 화면에 설 행이 있다.
 *
 * ## 로딩을 걷지 않는 이유 (라운드 104 트랙 SEARCH #3의 "골격 유지"와 같은 판단)
 *
 * 로딩 중에 컨트롤을 걷으면 달을 넘길 때마다 검색창·칩 줄·정렬 토글이 사라졌다 다시 서면서
 * 헤더 높이가 튄다 — 그때 사용자가 이미 치고 있던 검색어의 입력칸까지 언마운트된다. 로딩은
 * "0건"이라는 **사실을 아직 모르는** 상태이므로, 모르는 동안에는 아무것도 걷지 않는다.
 * 비활성 쿼리(비세션·아이 미선택)도 같은 이유로 `"loading"`이다: 로드가 확정되지 않았는데
 * "기록이 하나도 없다"고 판정하면 그 자체가 근거 없는 단정이다.
 *
 * ## 모집단의 뜻 — 이 화면이 실제로 아는 만큼만
 *
 * 이 화면은 **보고 있는 한 달**만 들고 있다(쿼리 키 `["expenses", childId, recordsYearMonth]`).
 * "이 계정에 기록이 한 건이라도 있는가"를 묻는 API는 **여전히 없다**. 그러므로 `"empty"`가
 * 뜻하는 것은 *"지금 이 화면이 보는 모집단이 0건이고, 그 반증도 손에 없다"* 이지
 * *"계정 전체가 0건임을 확인했다"* 가 아니다. 그 대신 걷는 것은 **필터 컨트롤뿐**이고 달
 * 이동(‹ ›)·월 선택 시트·리스트/달력 토글은 그대로 남긴다 — 빈 달에서 다른 달로 빠져나가는
 * 길이 하나도 막히지 않는다.
 *
 * ## 무엇이 바뀌었나 — 이월된 "알려진 한계"를 **새 요청 없이** 좁힌다
 *
 * 종전에는 위 문단이 곧 결론이었다(그때는 참이었다 — 계정 전체 유무를 묻는 수단이 판정에
 * 하나도 연결돼 있지 않았다). 그래서 **기록이 다른 달에만 있는 사용자가 빈 과거 달에 서면**
 * 그 달에서 검색창이 사라졌고, 이 화면의 검색은 월 스코프를 먼저 걸어야 "전체 기간에서 찾기"로
 * 올라가는 구조라 그 한 경로가 통째로 막혔다.
 *
 * 이제는 **이미 손에 들고 있는 것**이 그 반증을 준다(`hasKnownAccountRecords` — 새 엔드포인트도,
 * 새 요청도 0건이다). 둘 다 **양성 전용 신호**다: 참이면 "기록이 있다"가 확실하고, 거짓은
 * "없다"가 아니라 **"모른다"** 이다. 모르면 종전 판정 그대로 `"empty"`로 떨어진다 — 0건
 * 사용자의 첫 화면에서 컨트롤 무더기를 걷던 그 이득은 한 글자도 줄지 않는다.
 *
 *  1. **이미 캐시에 있는 다른 달 조회**(`["expenses", childId, *]`). 사용자가 ‹ ›로 달을 옮겨
 *     빈 달에 도착한 바로 그 경로가 직전 달을 캐시에 남긴다 — 신고된 그 시나리오를 정확히 덮는다.
 *     "전체 기간에서 찾기"가 모아 둔 21개월도 **같은 키**로 들어오므로 여기에 함께 잡힌다.
 *  2. **이 기기에 남은 이 아이의 미동기화 행**(달 무관 · 이미 구독 중인 오프라인 스냅샷).
 *
 * ## 남는 한계 하나와, 그것을 풀려면 무엇이 있어야 하는가 (고치지 않고 이월)
 *
 * 위 둘로도 못 덮는 경로가 하나 남는다: **빈 달만 지나온 사용자**(예: 이번 달 0건 → ‹ 지난달
 * 0건인데 기록은 석 달 전에 있다)와 **앱을 켜자마자 기록 탭으로 곧장 들어온 사용자**(이 저장소에
 * react-query 캐시 영속화가 0건이라 콜드 스타트의 캐시는 비어 있다). 그 경로에서는 둘 다
 * 거짓이라 종전과 같이 `"empty"`이고 검색창이 걷힌다.
 *
 * **무엇이 있으면 풀리나 — 새 API가 아니라 이미 있는 응답 하나다.** 홈 탭이 쓰는
 * `["home", childId]` 캐시가 `recentExpenses`(전 기간 최근 3건 · 선물 포함)와
 * `totalExpenseKrw`(전 기간 합계 · 선물 제외 — DNC-015)를 들고 있어, 그 둘 중 하나만 차 있어도
 * 계정 유무가 확정된다(선물만 기록한 계정이 합계 0으로 빈 계정처럼 읽히지 않도록 **둘 다**
 * 봐야 한다). 비용은 0이다: `getQueryData`로 **읽기만** 하면 쿼리가 켜지지 않아 요청이 생기지
 * 않고, 캐시가 없으면 그냥 `undefined`다(app/budget.tsx가 같은 두 키에 이미 세워 둔 규율).
 *
 * ⚠️ 이번 라운드가 그것을 배선하지 **않은** 이유는 설계가 아니라 소유다: `["home"` 문자열을
 * 갖는 비구독 화면은 `src/query/home-payload-consumers.test.ts`의
 * `HOME_CACHE_NON_SUBSCRIBER_SCREENS`에 **이유와 함께 등재**돼야 하는데(라운드 82 D #4 대장 —
 * 그 계약은 캐시 읽기를 정당한 접촉으로 이미 인정한다), 그 파일은 이 트랙의 소유가 아니다.
 * 다음 사람이 할 일은 그 대장에 `app/(tabs)/records.tsx` 한 줄(이유: 빈 달에서 계정 유무의
 * 반증을 읽기만 한다 · 요청 0건)을 더하고 여기 `homeSummary` 신호를 되살리는 것뿐이다.
 *
 * ⚠️ 그동안의 심각도: 판정이 틀려 `"empty"`로 떨어져도 **사용자는 갇히지 않는다** — 빈 달
 * 카드의 "이번 달 보기"(buildRecordsEmptyMonthState의 `go-current-month`)·달 이동 화살표·월
 * 선택 시트·아이 전환·탭바가 전부 이 게이트 밖이다. 즉 이 한계의 값은 **"불편"이지 "막다른
 * 길"이 아니다.**
 *
 * 화면 비의존(react-native를 import하지 않는다 — vitest가 RN을 렌더할 수 없다는 이 저장소의
 * 확립된 규율. records-sort.ts·records-date-groups.ts와 같은 결).
 */

/**
 * 기록 탭 표면의 갈래. 화면은 이 값 하나로 컨트롤 노출을 정한다.
 *
 * 종전에는 다섯이었다(그때는 참이었다 — 이 달 0건과 계정 0건을 가를 신호가 판정에 없었다).
 * 이제 여섯이다: `"empty-month"`가 "이 달만 비었음을 안다"를 `"empty"`("반증이 손에 없다")에서
 * 떼어 낸다. 근거는 머리말 "무엇이 바뀌었나".
 */
export type RecordsSurfaceMode = "loading" | "error" | "empty" | "empty-month" | "filtered-empty" | "list";

/**
 * **계정(정확히는 보고 있는 아이)에 기록이 한 건이라도 있는가** — 이미 손에 든 것만으로.
 *
 * ⚠️ **양성 전용**이다. `true`는 "있다"의 확증이고, `false`는 "없다"가 아니라 **"모른다"** 이다.
 * 판정부(`recordsSurfaceMode`)가 이 값을 그 방향으로만 쓴다: 참이면 `"empty"`를 취소하고,
 * 거짓이면 종전 판정을 한 글자도 바꾸지 않는다.
 *
 * 새 엔드포인트를 만들지 않았고 새 요청도 쏘지 않는다 — 두 신호가 전부 화면이 이미 들고 있는
 * 값이다(머리말 1·2). 셋째 후보와 그것이 막혀 있는 이유는 머리말 "남는 한계" 절에 있다. 이 화면은 달을 넘길 때마다 렌더되므로, 여기서 요청이 하나라도 늘면
 * 그 비용이 달 이동마다 반복된다.
 */
export function hasKnownAccountRecords(signals: {
  /**
   * 이미 react-query 캐시에 들어 있는 이 아이의 **다른 달** 조회 행 수들(요청 0건).
   * 보고 있는 달이 섞여 있어도 무해하다 — 그 달이 0건일 때만 이 함수가 불린다.
   */
  cachedMonthRecordCounts: readonly number[];
  /** 이 기기에 남은 이 아이의 미동기화 행 수(달 무관). */
  offlineRowCount: number;
}): boolean {
  if (signals.offlineRowCount > 0) return true;
  return signals.cachedMonthRecordCounts.some((count) => count > 0);
}

/**
 * 여섯 갈래 판정.
 *
 * 순서는 화면(`records.tsx`)의 `listEmpty` 분기 순서를 **그대로** 따른다(로딩 → 오류 → 필터
 * 0건 → 빈 달). 두 자리가 다른 순서로 물으면 같은 상태를 두고 본문과 헤더가 다른 말을 한다.
 *
 * `searchText`(입력값)와 `appliedSearchText`(디바운스 확정값)를 **둘 다** 본다: 확정 전
 * 350ms 동안 입력값만 차 있는 창이 있는데, 그때 확정값만 보면 사용자가 첫 글자를 치는 순간
 * 판정이 `"empty"`로 떨어져 **치고 있던 입력칸이 손 아래에서 사라진다**.
 */
export function recordsSurfaceMode(input: {
  /** 그 달 서버 조회가 로딩 중인가(`expenses.isLoading`). */
  isLoading: boolean;
  /** 그 달 서버 조회가 확정 실패했는가(`expenses.isError`). */
  isError: boolean;
  /** 서버 응답이 손에 있는가(`Boolean(expenses.data)`) — 비활성 쿼리에서는 false다. */
  hasData: boolean;
  /** **필터 이전** 모집단 건수(그 달 서버 행 + 오프라인 대기 행) — 월 요약 줄과 같은 셈이다. */
  populationCount: number;
  /** 필터를 적용한 뒤 화면에 설 행 수(`listData.length`). */
  visibleCount: number;
  /** 검색 입력칸의 **현재 값**(아직 확정되지 않았을 수 있다). */
  searchText: string;
  /** 디바운스로 확정되어 실제 필터에 걸린 검색어. */
  appliedSearchText: string;
  /** 고른 분류 칩. 고르지 않았으면 null("전체"). */
  categoryId: string | null;
  /**
   * 이 아이에게 기록이 있다는 것을 **이미 손에 든 캐시가 말하는가** — 위 `hasKnownAccountRecords`가
   * 만드는 값이다. 양성 전용이므로 false는 "없다"가 아니라 "모른다"다.
   *
   * ⚠️ 필드 이름을 함수 이름과 **일부러 다르게** 둔다(`has…` 접두 없음). 같은 이름을 export와
   * 속성 키 양쪽에 쓰면 사문 export 대장의 이름 훑기가 그 이름에 대해 눈이 먼다
   * (packages/test-utils dead-export-ledger의 `namesAlsoUsedAsProperty` — 오차가 거짓 초록
   * 쪽으로 난다). 한 글자 차이로 그 사각을 늘리지 않는다.
   */
  knownAccountRecords: boolean;
}): RecordsSurfaceMode {
  if (input.isLoading) return "loading";
  if (input.isError) return "error";
  // 비활성 쿼리(비세션·아이 미선택): 로딩도 오류도 아니지만 확정된 목록이 없다 — 머리말 참고.
  if (!input.hasData) return "loading";
  if (recordsFilterApplied(input)) return input.visibleCount > 0 ? "list" : "filtered-empty";
  // 필터가 없는데 보이는 행이 있다면 그것이 곧 모집단이다(전체 기간 스코프처럼 모집단 셈이
  // 월을 넘는 경우에도 "행이 있는데 빈 상태"라고 말하지 않는다).
  if (input.populationCount > 0 || input.visibleCount > 0) return "list";
  // 종전에는 여기서 곧장 "empty"였다(그때는 참이었다 — 이 달 0건 말고는 물을 수단이 없었다).
  // 이제는 손에 든 캐시가 "다른 달에 기록이 있다"고 말하면 이 달만 비었다고 말한다 — 그 사용자에게
  // 검색창을 남겨야 월 스코프 검색 → "전체 기간에서 찾기"로 올라가는 경로가 열려 있다.
  return input.knownAccountRecords ? "empty-month" : "empty";
}

/**
 * 필터가 하나라도 걸렸는가. 공백만 친 검색어는 필터가 아니다(필터 문구 모듈들이 쓰는
 * `normalizeRecordSearchText`와 같은 방향의 판정 — 여기서는 "걸렸는가"만 묻는다).
 */
function recordsFilterApplied(input: {
  searchText: string;
  appliedSearchText: string;
  categoryId: string | null;
}): boolean {
  if (input.categoryId !== null) return true;
  return input.searchText.trim().length > 0 || input.appliedSearchText.trim().length > 0;
}

/**
 * 검색 입력 · 최근 검색어 줄 · 분류 칩 줄 · 정렬 토글을 지금 세울 것인가.
 *
 * 걷는 갈래는 `"empty"` **하나뿐**이다. 특히 `"filtered-empty"`에서 참인 것이 이 함수의
 * 존재 이유다 — 0건을 만든 필터를 되돌릴 컨트롤이 그 화면에 남아 있어야 한다(머리말 ⚠️).
 *
 * 새로 생긴 `"empty-month"`도 참이다. 판정 줄은 종전 그대로(`mode !== "empty"`)인데, 갈래를
 * 나눈 쪽에서 이미 "이 달만 비었다"를 다른 이름으로 떼어 냈기 때문이다 — 걷을지 말지를 여기서
 * 다시 묻지 않는다(같은 사실을 두 자리가 각자 판정하면 언젠가 갈린다).
 */
export function areRecordsFilterControlsVisible(mode: RecordsSurfaceMode): boolean {
  return mode !== "empty";
}
