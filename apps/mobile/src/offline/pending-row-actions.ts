/**
 * GAP-062 #3 — 동기화 상태 화면의 **대기 행에서 취할 수 있는 행동**을 고르는 순수 판정.
 *
 * ## 무엇이 문제였나
 *
 * 기록 탭의 오프라인 대기 행은 탭하면 동기화 상태 화면으로 간다(app/(tabs)/records.tsx —
 * "아직 서버 id가 없어 상세로 갈 수도, 같은 삭제 경로를 탈 수도 없다"). 그런데 그 목적지의 대기
 * 행에는 **문장 한 줄뿐이었다**("연결되면 자동으로 반영할게요."). 실패 행에는 재시도·삭제·고쳐서
 * 다시 보내기가, 충돌 행에는 세 갈래가 있는데 대기 행에만 아무것도 없었다.
 *
 * 그래서 비행기 모드에서 38,500원을 385,000원으로 잘못 적으면, 그 값은 즉시 홈 히어로·기록 탭 월
 * 합계·예산 경고·정기 지출 "기록됨" 판정에 들어가고 연결이 돌아올 때까지 사용자가 **고칠 수도
 * 지울 수도 없다**. 오프라인 우선을 표방하는 앱에서 오프라인이 곧 편집 불가 상태였다.
 *
 * ## 왜 "버리기" 하나인가 (정직한 최소치)
 *
 * "고쳐서 다시 보내기"의 기계장치는 이미 있다(src/expenses/failed-row-prefill.ts). 하지만 대기
 * 행에 그것을 열면 **실패 행에는 없던 경합**이 생긴다: 프리필 시트를 채우는 사이에 연결이 돌아와
 * flush가 성공하면 폐기 대상이던 원본이 이미 서버에 확정돼, 저장이 같은 지출을 한 건 더 만든다
 * (실패 행은 flush가 건드리지 않으므로 이 경합이 없다). 그래서 이번 라운드는 버리기까지다.
 *
 * ## 어떤 대기 행이 버릴 수 있는 행인가
 *
 * `syncState !== "synced"`인 행은 한 가지가 아니다(같은 갈래를 이미 네 자리가 다르게 다룬다 —
 * src/reports/pending-scope-notice.ts 머리말). 대기 행도 셋이다:
 *
 *  1. **생성 대기**(`canonicalId === null`): 서버가 이 지출을 아직 모른다. 버리면 이 기기에서
 *     사라지고 그것으로 끝이다 — 되돌릴 수 없지만, 어긋날 서버 값도 없다. **이 갈래만 대상이다.**
 *  2. **수정 대기**(`canonicalId !== null`): 서버에는 이 지출이 옛 값으로 살아 있다. 여기서
 *     버리는 것은 기록이 아니라 **아직 보내지 못한 변경**이고, 그러면 서버 값이 목록·합계로
 *     되돌아온다(reconciliation의 `staleServerCanonicalIds`). 결과가 다르므로 같은 단어로 부를 수
 *     없다 — "버리기"라고 적힌 버튼이 기록을 되살리면 그 라벨이 거짓이다.
 *  3. **삭제 대기**(`pendingDelete`): 버리면 **삭제 요청이 취소돼** 지웠다고 믿은 지출이 목록에
 *     다시 선다. 2번과 같은 이유로, 그리고 방향이 정반대라 더더욱 같은 버튼일 수 없다.
 *
 * 2·3은 "변경 취소"라는 **다른 행동**이고 문구도 결과도 다르다. 지어내지 않는 쪽을 택해 이번
 * 라운드에서는 붙이지 않는다(그 행들은 종전 그대로 한 줄 안내만 갖는다).
 *
 * ## 전송 중인 행은 절대 대상이 아니다
 *
 * `syncState === "syncing"`은 요청이 **이미 나가 있다**는 뜻이다(sync-engine.ts flushOutboxPass가
 * 보내기 직전에 표시한다). 그 행을 지우면 로컬에서는 사라지지만 서버는 요청을 받아 지출을
 * 만든다 — 앱 어디에서도 손댈 수 없는 **고아 지출**이다. 그래서 판정은 `"pending"` 하나만
 * 통과시킨다(`"failed"`·`"conflict"`는 각자의 행이 이미 자기 액션을 갖고 있다).
 *
 * 화면의 스냅샷은 한 박자 낡을 수 있으므로 이 판정은 **두 번** 쓰인다: 버튼을 그릴 때(여기)와,
 * 누른 뒤 저장소에서 행을 다시 읽어 확인할 때(sync-engine.ts `discardPendingMutation` — 그쪽은
 * outbox의 `inFlight` 표시까지 함께 본다). 일괄 액션이 스냅샷 대신 저장소를 읽는 것과 같은 이유다
 * (SYNC-127 `listFailedLocalIds` 주석).
 *
 * React/react-native/저장소에 의존하지 않는다 — 화면 밖에서 vitest로 검증하기 위해서다.
 */

/** `LocalExpenseRow`에서 이 판정에 필요한 것만 (src/offline/types.ts와 구조 호환). */
export type PendingRowActionRow = {
  syncState: string;
  /** 삭제가 큐에 올라간 행. 값을 모르는 픽스처는 종전대로 삭제 대기가 아닌 행으로 읽힌다. */
  pendingDelete?: boolean | null;
  /** 서버가 이 지출에 부여한 id. null/undefined면 서버는 이 기록을 아직 모른다. */
  canonicalId?: string | null;
};

/**
 * 이 대기 행에 "버리기"를 붙일 수 있는가. 규칙은 이 파일 머리말이 전부다 —
 * 전송 중이 아니고(`pending`), 서버가 아직 모르는 **생성 대기** 행일 때만 참이다.
 */
export function isDiscardablePendingRow(row: PendingRowActionRow): boolean {
  if (row.syncState !== "pending") return false;
  if (row.pendingDelete) return false;
  // 서버 id가 **있다고 말하는 값**일 때만 서버 지출을 가리키는 행으로 본다(null·undefined·""는
  // 전부 "서버가 아직 모른다"). 타입상 ""는 나오지 않지만, 나온다 해도 판정이 갈리지 않는다.
  return !row.canonicalId;
}
